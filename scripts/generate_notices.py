"""Generate THIRD_PARTY_NOTICES.md and a CycloneDX SBOM from the lock file.

The component list is the runtime closure of the project with all its extras, taken from
``uv export`` (so it is exactly what ``uv.lock`` pins). Licences are read from the installed
distributions' metadata, which needs the extras installed; where one is not installed the licence
is marked as unknown rather than guessed. ``--check`` compares only the names and versions with the
committed SBOM, which is what a CI job can verify without installing every extra.

    uv run python scripts/generate_notices.py            # rewrite the two files
    uv run python scripts/generate_notices.py --check    # exit 1 if they are out of date
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata as metadata
import json
import re
import subprocess
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
SBOM = ROOT / "sbom.cdx.json"
_LINE = re.compile(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)")


def locked_components() -> list[tuple[str, str]]:
    done = subprocess.run(
        ["uv", "export", "--frozen", "--no-dev", "--all-extras", "--no-emit-project",  # noqa: S607
         "--no-hashes", "--format", "requirements-txt"],
        capture_output=True, text=True, check=True, cwd=ROOT,
    )  # fmt: skip
    found = {}
    for line in done.stdout.splitlines():
        match = _LINE.match(line.strip())
        if match:
            found[match.group(1).lower().replace("_", "-")] = match.group(2)
    return sorted(found.items())


# Windows-only wheels that a Linux environment never installs; their published licences.
DECLARED = {
    "colorama": "BSD-3-Clause (declared by the project; Windows only, not installed here)",
    "win32-setctime": "MIT (declared by the project; Windows only, not installed here)",
}


def _from_licence_file(name: str) -> str | None:
    try:
        files = metadata.files(name) or []
    except metadata.PackageNotFoundError:
        return None
    for item in files:
        if "licenses" in item.parts and item.name.upper().startswith(("LICENSE", "COPYING")):
            first = item.read_text().strip().splitlines()[0].strip()
            for key, label in (("MIT", "MIT"), ("Apache", "Apache-2.0"), ("BSD", "BSD")):
                if first.startswith(key):
                    return f"{label} (from its licence file)"
    return None


def licence_of(name: str) -> str:
    if name in DECLARED:
        return DECLARED[name]
    try:
        info = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "unknown (not installed here)"
    expression = info.get("License-Expression")
    if expression:
        return str(expression)
    classifiers = [c.split("::")[-1].strip() for c in info.get_all("Classifier") or []
                   if c.startswith("License ::")]  # fmt: skip
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    text = (info.get("License") or "").strip()
    if text:
        return text.splitlines()[0][:80]
    return _from_licence_file(name) or "unknown"


def home_of(name: str) -> str:
    try:
        info = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return ""
    return str(info.get("Home-page") or "") or next(
        (u.split(",", 1)[-1].strip() for u in info.get_all("Project-URL") or []), ""
    )


def render_notices(components: list[tuple[str, str]]) -> str:
    lines = [
        "# Third-party notices",
        "",
        "Generated by `scripts/generate_notices.py` from `uv.lock` (runtime closure, all extras).",
        "Licences come from the installed package metadata or licence file; `unknown` means they",
        "do not say, and the package must be checked before a release. The licence of this",
        "project itself has not been chosen.",
        "",
        "| Package | Version | Licence |",
        "|---|---|---|",
    ]
    for name, version in components:
        lines.append(f"| {name} | {version} | {licence_of(name).replace('|', '/')} |")
    return "\n".join(lines) + "\n"


def render_sbom(components: list[tuple[str, str]]) -> str:
    digest = hashlib.sha256(json.dumps(components).encode()).hexdigest()
    document = {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "serialNumber": f"urn:uuid:{uuid.UUID(digest[:32])}",
        "version": 1,
        "metadata": {
            "component": {
                "type": "application",
                "name": "independent-rag-engine",
                "bom-ref": "root",
            },
            "tools": {"components": [{"type": "application", "name": "generate_notices.py"}]},
        },
        "components": [
            {
                "type": "library",
                "bom-ref": f"pkg:pypi/{name}@{version}",
                "name": name,
                "version": version,
                "purl": f"pkg:pypi/{name}@{version}",
                "licenses": [{"license": {"name": licence_of(name)}}],
            }
            for name, version in components
        ],
    }
    return json.dumps(document, indent=2, sort_keys=True) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    components = locked_components()
    if args.check:
        committed = json.loads(SBOM.read_text(encoding="utf-8"))
        have = sorted((c["name"], c["version"]) for c in committed["components"])
        if have != components:
            sys.stderr.write("sbom.cdx.json is out of date: run scripts/generate_notices.py\n")
            return 1
        notices = NOTICES.read_text(encoding="utf-8")
        missing = [n for n, v in components if f"| {n} | {v} |" not in notices]
        if missing:
            sys.stderr.write(f"THIRD_PARTY_NOTICES.md lacks: {', '.join(missing[:5])}\n")
            return 1
        return 0
    NOTICES.write_text(render_notices(components), encoding="utf-8")
    SBOM.write_text(render_sbom(components), encoding="utf-8")
    print(f"{len(components)} components")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
